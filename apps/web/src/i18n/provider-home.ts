const catalogs: Record<Locale, Record<ProviderHomeMessageKey, string>> = { en, ja }

export function providerHomeText(locale: Locale, key: ProviderHomeMessageKey, params: Params = {}): string {
  const template = catalogs[locale][key]
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) => {
    const value = params[name]
    return value === undefined ? match : String(value)
  })
}

export function providerHomeCoverage(locale: Locale, platform: Platform): string {
  return providerHomeText(locale, platform === 'twitch' ? 'coverage.twitch' : 'coverage.kick')
}

export function providerHomeLede(locale: Locale, platform: Platform): string {
  return providerHomeText(locale, platform === 'twitch' ? 'lede.twitch' : 'lede.kick')
}

export type { ProviderHomeMessageKey }
