const catalogs: Record<Locale, Record<HeatmapMessageKey, string>> = { en, ja }

export function heatmapText(locale: Locale, key: HeatmapMessageKey, params: Params = {}): string {
  return catalogs[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`))
}

export function heatmapStateLabel(locale: Locale, state: string): string {
  const key = `state.${state}` as HeatmapMessageKey
  return key in catalogs[locale] ? heatmapText(locale, key) : state
}

export function heatmapNumber(locale: Locale, value: number): string {
  return new Intl.NumberFormat(locale === 'ja' ? 'ja-JP' : 'en-US').format(Number.isFinite(value) ? value : 0)
}

export function heatmapDateTime(locale: Locale, value: string): string {
  const date = new Date(value)
  if (!Number.isFinite(date.getTime())) return heatmapText(locale, 'common.unavailable')
  return new Intl.DateTimeFormat(locale === 'ja' ? 'ja-JP' : 'en-US', {
    year: 'numeric',
    month: locale === 'ja' ? 'numeric' : 'short',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    timeZoneName: 'short',
  }).format(date)
}

export function heatmapReason(locale: Locale, reason: string): string {
  if (locale === 'en') return reason
  const known: Record<string, HeatmapMessageKey> = {
    'Collector reports more records beyond the current snapshot scope.': 'reason.more',
    'Activity signal is unavailable for the current observed field.': 'reason.activityUnavailable',
    'Activity was not sampled in the current window.': 'reason.activityNotSampled',
    'Collector health is degraded.': 'reason.collectorDegraded',
    'Snapshot source mode is unknown.': 'reason.sourceUnknown',
    'The latest successful snapshot is delayed.': 'reason.delayed',
  }
  const key = known[reason]
  return key ? heatmapText(locale, key) : reason
}

export function heatmapMomentumLabel(locale: Locale, value: number, flat = false): string {
  if (value > 0.02) return heatmapText(locale, 'momentum.rising')
  if (value < -0.02) return heatmapText(locale, 'momentum.falling')
  return heatmapText(locale, flat ? 'momentum.flat' : 'momentum.stable')
}

export function heatmapActivityLegend(locale: Locale, state: string): string {
  if (state === 'available') return heatmapText(locale, 'legend.activity.available')
  if (state === 'zero') return heatmapText(locale, 'legend.activity.zero')
  if (state === 'unavailable') return heatmapText(locale, 'legend.activity.unavailable')
  return heatmapText(locale, 'legend.activity.notSampled')
}

export function heatmapObservationDuration(locale: Locale, minutes: number | null, truncated = false, bucketMinutes = 5): string {
  if (!Number.isFinite(minutes) || (minutes ?? -1) < 0) return heatmapText(locale, 'common.unavailable')
  const safeMinutes = minutes ?? 0
  const bucket = Number.isFinite(bucketMinutes) && bucketMinutes > 0 ? Math.round(bucketMinutes) : 5
  if (locale === 'en') {
    if (safeMinutes === 0) return `Less than ${bucket}m`
    const rounded = Math.round(safeMinutes)
    const hours = Math.floor(rounded / 60)
    const rest = rounded % 60
    const value = hours === 0 ? `${rest}m` : rest === 0 ? `${hours}h` : `${hours}h ${rest}m`
    return truncated ? `At least ${value}` : value
  }
  if (safeMinutes === 0) return `${bucket}分未満`
  const rounded = Math.round(safeMinutes)
  const hours = Math.floor(rounded / 60)
  const rest = rounded % 60
  const value = hours === 0 ? `${rest}分` : rest === 0 ? `${hours}時間` : `${hours}時間${rest}分`
  return truncated ? `少なくとも${value}` : value
}
